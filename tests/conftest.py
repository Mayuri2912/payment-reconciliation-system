"""Collects real pytest outcomes and writes docs/TEST_RESULTS.md after every run.

Each test documents itself in its docstring (ID, Objective, Input, Expected) and records what it
actually observed with the `actual` fixture. The table is generated from the executed run, never typed by hand.
"""
import re
import sys
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

RESULTS = []


@pytest.fixture
def actual(request):
    box = []
    request.node._actual = box
    return box


@pytest.hookimpl(hookwrapper=True)
def pytest_runtest_makereport(item, call):
    outcome = yield
    report = outcome.get_result()
    if report.when == "call" or (report.when == "setup" and report.failed):
        doc = item.function.__doc__ or ""
        fields = {}
        for key in ("ID", "Objective", "Input", "Expected"):
            match = re.search(rf"^\s*{key}:\s*(.+)$", doc, re.M)
            fields[key] = match.group(1).strip() if match else ""
        error = ""
        if report.failed:
            error = report.longreprtext.strip().splitlines()[-1][:200]
        RESULTS.append({**fields, "name": item.name, "outcome": report.outcome.upper(),
                        "actual": " | ".join(getattr(item, "_actual", [])) or error})


def pytest_sessionfinish(session, exitstatus):
    if not RESULTS:
        return
    passed = sum(1 for r in RESULTS if r["outcome"] == "PASSED")
    lines = ["# Test results (generated by the last pytest run)", "",
             f"Executed: {len(RESULTS)} tests, {passed} passed, {len(RESULTS) - passed} failed.", "",
             "| Test case | Objective | Input / scenario | Expected result | Actual result | Status |",
             "|---|---|---|---|---|---|"]
    for r in sorted(RESULTS, key=lambda x: x["ID"]):
        cells = [r["ID"] or r["name"], r["Objective"], r["Input"], r["Expected"], r["actual"], r["outcome"]]
        lines.append("| " + " | ".join(c.replace("|", "/") for c in cells) + " |")
    (ROOT / "docs").mkdir(exist_ok=True)
    (ROOT / "docs" / "TEST_RESULTS.md").write_text("\n".join(lines) + "\n")
